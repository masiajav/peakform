import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import { VOD_NOTEBOOK_KEY } from '../../src/lib/vod-review-notebook'

const path = '/guides/review-vod-overwatch-espanol'

test('a player can record, compare, restore and export a review without submitting notes', async ({ page }) => {
  const errors: string[] = []
  const sentNotes: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.postData()?.includes('Gibraltar-test-notes')) sentNotes.push(request.url()) })
  await page.goto(path)
  const notebook = page.getByRole('region', { name: 'Cuaderno de revisión', exact: true })
  await expect(notebook.getByRole('status')).toContainText('este navegador')
  expect(await page.evaluate(key => localStorage.getItem(key), VOD_NOTEBOOK_KEY)).toBeNull()
  await expect(notebook.getByRole('button', { name: 'Exportar revisión', exact: true })).toBeDisabled()
  await notebook.getByLabel('Héroe', { exact: true }).selectOption('ana')
  await notebook.getByLabel('Mapa', { exact: true }).fill('Gibraltar-test-notes')
  await notebook.getByLabel('Pregunta de la revisión', { exact: true }).fill('¿Por qué pierdo la altura?')
  const first = notebook.getByRole('group', { name: 'Pelea 1', exact: true })
  await first.getByLabel('Minuto (mm:ss)', { exact: true }).fill('2:90')
  await notebook.getByRole('button', { name: 'Exportar revisión', exact: true }).click()
  await expect(notebook.getByRole('status')).toContainText('Revisa los minutos')
  await first.getByLabel('Minuto (mm:ss)', { exact: true }).fill('02:40')
  await first.getByLabel('Qué información tenías', { exact: true }).fill('Vi a Winston preparar el salto')
  await first.getByLabel('Qué hiciste y qué pasó', { exact: true }).fill('Seguí apuntando al Tank')
  await first.getByLabel('Qué alternativa había', { exact: true }).fill('Bajar por detrás')
  await notebook.getByRole('button', { name: 'Añadir pelea', exact: true }).click()
  await notebook.getByRole('group', { name: 'Pelea 2', exact: true }).getByLabel('Qué hiciste y qué pasó', { exact: true }).fill('Roté antes de perder la visión')
  await notebook.getByLabel('Qué practicarás en la siguiente partida', { exact: true }).fill('Preparar una salida antes de disparar')
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!).practice, VOD_NOTEBOOK_KEY)).toBe('Preparar una salida antes de disparar')
  await page.reload()
  await expect(notebook.getByLabel('Héroe', { exact: true })).toHaveValue('ana')
  await expect(first.getByLabel('Qué alternativa había', { exact: true })).toHaveValue('Bajar por detrás')
  await expect(notebook.getByRole('group', { name: 'Pelea 2', exact: true }).getByLabel('Qué hiciste y qué pasó', { exact: true })).toHaveValue('Roté antes de perder la visión')
  const downloadPromise = page.waitForEvent('download')
  await notebook.getByRole('button', { name: 'Exportar revisión', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('replaid-lab-revision.txt')
  const text = await readFile((await download.path())!, 'utf8')
  expect(text).toContain('Héroe: Ana')
  expect(text).toContain('PELEA 1 | 02:40')
  expect(text).toContain('Roté antes de perder la visión')
  expect(text).toContain('Preparar una salida antes de disparar')
  await notebook.getByRole('button', { name: 'Añadir pelea', exact: true }).click()
  await expect(notebook.getByRole('button', { name: 'Añadir pelea', exact: true })).toBeDisabled()
  await expect(notebook.getByRole('group', { name: /^Pelea \d$/ })).toHaveCount(3)
  expect(sentNotes).toEqual([])
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await expect(page.locator('.ad-slot,ins.adsbygoogle,script[src*="adsbygoogle"]')).toHaveCount(0)
  await notebook.screenshot({ path: `reports/vod-notebook/filled-${test.info().project.name}.png` })
})

test('role-specific examples and hero choices do not turn Sombra back into DPS', async ({ page }) => {
  await page.goto(path)
  const notebook = page.getByRole('region', { name: 'Cuaderno de revisión', exact: true })
  await notebook.getByRole('button', { name: 'DPS', exact: true }).click()
  await expect(notebook.getByRole('option', { name: 'Sombra', exact: true })).toHaveCount(0)
  await notebook.getByText('Caso de práctica: Genji consigue una baja y no puede salir', { exact: true }).click()
  await expect(notebook).toContainText('Situación ficticia')
  await expect(notebook).toContainText('carga')
  await notebook.getByRole('button', { name: 'Tank', exact: true }).click()
  await expect(notebook).toContainText('Winston aterriza sin ayuda')
  await notebook.getByRole('button', { name: 'Support', exact: true }).click()
  await expect(notebook.getByRole('option', { name: 'Sombra', exact: true })).toHaveCount(1)
  await expect(notebook).toContainText('Ana pierde la altura ante Winston')
})

test('unsupported storage is preserved until an explicit confirmed clear', async ({ page }) => {
  await page.addInitScript(key => {
    localStorage.setItem(key, '{unsupported')
    localStorage.setItem('unrelated-notebook-test', 'keep')
  }, VOD_NOTEBOOK_KEY)
  await page.goto(path)
  const notebook = page.getByRole('region', { name: 'Cuaderno de revisión', exact: true })
  await expect(notebook.getByRole('status')).toContainText('no es compatible')
  await notebook.getByLabel('Pregunta de la revisión', { exact: true }).fill('Una nota nueva')
  expect(await page.evaluate(key => localStorage.getItem(key), VOD_NOTEBOOK_KEY)).toBe('{unsupported')
  await notebook.getByRole('button', { name: 'Borrar revisión', exact: true }).click()
  await notebook.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(notebook.getByLabel('Pregunta de la revisión', { exact: true })).toHaveValue('Una nota nueva')
  await notebook.getByRole('button', { name: 'Borrar revisión', exact: true }).click()
  await notebook.getByRole('button', { name: 'Borrar', exact: true }).click()
  await expect(notebook.getByLabel('Pregunta de la revisión', { exact: true })).toHaveValue('')
  expect(await page.evaluate(() => localStorage.getItem('unrelated-notebook-test'))).toBe('keep')
})

test('unavailable local storage leaves an editable and exportable notebook', async ({ page }) => {
  await page.addInitScript(() => { Storage.prototype.getItem = () => { throw new DOMException('blocked', 'SecurityError') } })
  await page.goto(path)
  const notebook = page.getByRole('region', { name: 'Cuaderno de revisión', exact: true })
  await expect(notebook.getByRole('status')).toContainText('guardado local no está disponible')
  await notebook.getByLabel('Pregunta de la revisión', { exact: true }).fill('Puedo revisar sin almacenamiento')
  await expect(notebook.getByRole('button', { name: 'Exportar revisión', exact: true })).toBeEnabled()
})
