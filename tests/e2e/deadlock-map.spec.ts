import {test,expect} from '@playwright/test'
import {previewSignature} from '../../src/lib/editorial-preview-token'
const path='/deadlock/maps/la-ciudad'
function pagePath(){const id=process.env.MAP_PREVIEW_ID;if(!id)return path;const expires=String(Date.now()+300000);return `/editorial-preview/${id}?expires=${expires}&token=${previewSignature(id,expires,process.env.SUPABASE_SERVICE_ROLE_KEY??'')}`}

test('map layers, orientation, resources and zoom work without page overflow',async({page})=>{
 await page.goto(pagePath())
 const atlas=page.getByRole('region',{name:'Explorar el mapa de Deadlock',exact:true})
 await expect(atlas).toBeVisible()
 await expect(atlas.locator('[data-map-group="guardians"] circle')).toHaveCount(6)
 await atlas.getByRole('button',{name:'Túneles centrales',exact:true}).click()
 await expect(atlas.locator('[data-map-canvas]')).toHaveAttribute('aria-label',/Túneles centrales/)
 await atlas.getByRole('button',{name:'Conductos pequeños',exact:true}).click()
 await expect(atlas.locator('[data-map-canvas]')).toHaveAttribute('aria-label',/Conductos pequeños/)
 await atlas.getByRole('button',{name:'Zafiro abajo',exact:true}).click()
 await expect(atlas.locator('[data-map-orientation]')).toHaveAttribute('transform','rotate(180 500 500)')
 await atlas.getByRole('button',{name:'Acercar mapa',exact:true}).click()
 await expect(atlas.locator('output')).toHaveText('150 %')
 const viewport=atlas.getByRole('region',{name:'Plano ampliable; usa las flechas para desplazarte'})
 expect(await viewport.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true)
 await atlas.getByRole('button',{name:'Recursos',exact:true}).click()
 await expect(atlas.locator('[data-map-group="guardians"]')).toHaveCount(0)
 await expect(atlas.locator('[data-map-group="medium-camps"]>g')).toHaveCount(25)
 await atlas.getByRole('button',{name:'Limpiar',exact:true}).click()
 await expect(atlas.locator('[data-map-group]')).toHaveCount(0)
 await atlas.getByLabel('Mostrar las tres tirolinas',{exact:true}).uncheck()
 await expect(atlas.locator('[data-map-lane]')).toHaveCount(0)
 await atlas.getByLabel('Qué significa cada elemento',{exact:true}).selectOption('urn-spawns')
 await expect(atlas.locator('[data-map-group="urn-spawns"]>g')).toHaveCount(6)
 await expect(atlas).toContainText('no son seis urnas simultáneas')
 await atlas.getByRole('button',{name:'Restablecer mapa',exact:true}).click()
 await expect(atlas.locator('output')).toHaveText('100 %')
 await expect(atlas.getByRole('button',{name:'Ámbar abajo',exact:true})).toHaveAttribute('aria-pressed','true')
 await atlas.locator('summary').click()
 await atlas.getByRole('checkbox',{name:'Mostrar Cajas resistentes',exact:true}).check()
 await expect(atlas.locator('[data-map-group="tough-crates"] circle')).toHaveCount(74)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
})

test('map guide has readable illustrations, chapters and actionable explanations',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto(pagePath())
 const contents=page.getByRole('navigation',{name:'En este artículo'})
 await expect(contents).not.toBeVisible()
 await page.locator('.game-map-toc>summary').click()
 await expect(contents.getByRole('link')).toHaveCount(32)
 await contents.getByRole('link',{name:'Rejuvenecedor: el cristal se reclama después de caer',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Rejuvenecedor: el cristal se reclama después de caer',exact:true})).toBeVisible()
 const pictures=page.locator('.deadlock-map-figure img');await expect(pictures).toHaveCount(11)
 for(const picture of await pictures.all()){await picture.scrollIntoViewIfNeeded();await expect(picture).toBeVisible();await expect(picture).not.toHaveAttribute('alt','')}
 await page.waitForFunction(()=>[...document.querySelectorAll('.deadlock-map-figure img')].every(i=>(i as HTMLImageElement).complete&&(i as HTMLImageElement).naturalWidth>0))
 const faq=page.locator('.game-faq').filter({has:page.getByText('¿Cada compañero tiene tres reapariciones con el Rejuvenecedor?',{exact:true})});await faq.locator('summary').click();await expect(faq.locator('p')).toContainText('reserva del equipo')
 expect(await page.locator('main').innerText()).not.toMatch(/Codex|snapshot|propuesta editorial|contenido automatizado/i)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
 expect(errors).toEqual([])
})

test('published map is discoverable from the game, search, menu and sitemap',async({page,request,isMobile})=>{
 test.skip(Boolean(process.env.MAP_PREVIEW_ID),'Requires published map')
 await page.goto('/deadlock')
 await page.getByRole('link',{name:'Explora el mapa de Deadlock',exact:false}).click()
 await expect(page).toHaveURL(new RegExp(path+'$'))
 if(isMobile)await page.getByRole('button',{name:'Abrir navegación',exact:true}).click()
 await page.getByRole('navigation',{name:'Navegación pública',exact:true}).getByRole('link',{name:'Mapa',exact:true}).click()
 await expect(page).toHaveURL(/\/deadlock\/maps$/)
 await page.getByLabel('Buscar en mapa',{exact:true}).fill('objetivos')
 await page.getByRole('button',{name:'Buscar',exact:true}).click()
 await expect(page.locator('.game-content-card')).toHaveCount(1)
 await page.locator('.game-content-card').click()
 await expect(page).toHaveURL(new RegExp(path+'$'))
 expect(await(await request.get('/sitemap.xml')).text()).toContain(path)
})
